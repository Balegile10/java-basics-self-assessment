
package q22.comparetwonumbers;

public class Q22CompareTwoNumbers {

    public static void main(String[] args) {
        int n1 = 25;
        int n2 = 39;

        if (n1 != n2) System.out.println(n1 + " != " + n2);
        if (n1 < n2) System.out.println(n1 + " < " + n2);
        if (n1 <= n2) System.out.println(n1 + " <= " + n2);
    }
    
}
