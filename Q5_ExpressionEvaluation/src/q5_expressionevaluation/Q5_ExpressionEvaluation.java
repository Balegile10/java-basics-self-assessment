
package q5_expressionevaluation;


public class Q5_ExpressionEvaluation {

    
    public static void main(String[] args) {
        // Given values
        double a = 5;
        double b = 3;
        double c = 4;
        double d = 2;
        double e = 6;
        double f = 1.5;

        // Compute (a + b) / c + (d * e) - f 
        double result = (a + b) / c + (d * e) - f;

        System.out.println("Result: " + result);
    }
    
}
